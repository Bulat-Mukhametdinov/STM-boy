static const uint8_t blank[5] = {0,0,0,0,0};

const uint8_t *Font5x7_GetGlyph(char c)
{
  for (unsigned i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++)
  {
    if (glyphs[i].c == c)
    {
      return glyphs[i].g;
    }
  }
  return blank;
}
